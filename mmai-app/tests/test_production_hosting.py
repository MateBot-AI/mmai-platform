def test_own_anthropic_key_mode(monkeypatch):
    for k in ("ANTHROPIC_BASE_URL", "ANTHROPIC_AUTH_TOKEN", "MMAI_AI_URL_VAR", "MMAI_AI_TOKEN_VAR", "MMAI_AI_MODE", "MMAI_AI_MODEL", "MMAI_AI_FAST_MODEL"):
        monkeypatch.delenv(k, raising=False)
    monkeypatch.setenv("ANTHROPIC_API_KEY", "sk-ant-test")
    assert ai.ai_mode() == "own-key" and ai.model_name() == ai.APPROVED_MODEL == "claude-sonnet-5-5"
    assert ai.model_name(fast=True) == ai.APPROVED_MODEL, "T13: no separate fast model"
    monkeypatch.setenv("ANTHROPIC_BASE_URL", "https://proxy.example")   # the development proxy: sandbox mode, sandbox ids
    assert ai.ai_mode() == "sandbox" and ai.model_name() == ai.SANDBOX_MODEL
    monkeypatch.setenv("MMAI_AI_MODE", "own-key")                        # explicit override wins
    assert ai.ai_mode() == "own-key"
    monkeypatch.setenv("MMAI_AI_MODEL", "claude-custom-1")               # T13: with a real key an env override cannot switch the model
    assert ai.model_name() == ai.APPROVED_MODEL and ai.model_override_ignored() == "claude-custom-1"
    assert ai.model_policy()["is_approved"] is True and ai.model_policy()["override_ignored"] == "claude-custom-1"
    monkeypatch.setenv("MMAI_AI_MODEL", ai.APPROVED_MODEL)              # confirming the approved id is fine
    assert ai.model_override_ignored() is None
    monkeypatch.delenv("ANTHROPIC_API_KEY")
    assert ai.ai_mode() == "none"


