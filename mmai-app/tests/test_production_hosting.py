# ---------------------------------------------------------------- SQL translation (runs everywhere)
def test_translate_placeholders_and_literal_percent():
    assert dbmod.translate_sql("SELECT * FROM t WHERE a=? AND b LIKE '%GP%'", True) == "SELECT * FROM t WHERE a=%s AND b LIKE '%%GP%%'"
    assert dbmod.translate_sql("SELECT * FROM t WHERE b LIKE '%GP%'", False) == "SELECT * FROM t WHERE b LIKE '%GP%'"


def test_translate_insert_or_ignore_and_replace():
    assert dbmod.translate_sql("INSERT OR IGNORE INTO group_members(group_id, enquiry_id) VALUES (?, ?)", True) == \
        "INSERT INTO group_members(group_id, enquiry_id) VALUES (%s, %s) ON CONFLICT DO NOTHING"
    out = dbmod.translate_sql("INSERT OR REPLACE INTO group_apartments(group_id, apartment_id, rank, note) VALUES (?, ?, ?, ?)", True)
    assert out == ("INSERT INTO group_apartments(group_id, apartment_id, rank, note) VALUES (%s, %s, %s, %s) "
                   "ON CONFLICT (group_id, apartment_id) DO UPDATE SET rank=EXCLUDED.rank, note=EXCLUDED.note")


def test_translate_lastrowid_and_desc_nulls_last():
    assert dbmod.translate_sql("SELECT last_insert_rowid()", False) == "SELECT lastval()"
    assert dbmod.translate_sql("SELECT id FROM groups ORDER BY ai_rating DESC, id DESC NULLS LAST", False) == \
        "SELECT id FROM groups ORDER BY ai_rating DESC NULLS LAST, id DESC NULLS LAST"
    assert "description" in dbmod.translate_sql("SELECT description FROM t", False)


def test_translate_ddl():
    assert dbmod.translate_ddl("id INTEGER PRIMARY KEY AUTOINCREMENT, score REAL, realname TEXT") == \
        "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, score DOUBLE PRECISION, realname TEXT"


def test_adapt_params_bool_and_dates():
    from datetime import date, datetime
    assert dbmod._adapt_params((True, False, date(2026, 10, 30), datetime(2026, 10, 30, 1, 2, 3), "x", None, 1.5)) == \
        [1, 0, "2026-10-30", "2026-10-30T01:02:03", "x", None, 1.5]


def test_pgrow_behaves_like_sqlite_row():
    r = dbmod.PgRow((1, "Bill"), ("id", "name"), {"id": 0, "name": 1})
    assert r[0] == 1 and r["name"] == "Bill" and dict(r) == {"id": 1, "name": "Bill"} and list(r) == [1, "Bill"]
    assert r.keys() == ["id", "name"] and "id" in r and r == (1, "Bill") and len(r) == 2


def test_sqlite_is_default_when_database_url_unset(monkeypatch):
    monkeypatch.delenv("DATABASE_URL", raising=False)
    assert not dbmod.is_postgres() and dbmod.backend_name() == "sqlite"
