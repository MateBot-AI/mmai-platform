# ---------------------------------------------------------------- live Postgres (only when a test database is given)
PG_URL = os.environ.get("MMAI_TEST_DATABASE_URL") or (os.environ.get("DATABASE_URL") if os.environ.get("DATABASE_URL", "").startswith("postgres") else "")


@pytest.mark.skipif(not PG_URL, reason="set MMAI_TEST_DATABASE_URL=postgresql://... to run against a live Postgres")
def test_postgres_schema_upserts_identity_and_savepoints():
    c = dbmod.PgConnection(PG_URL)
    try:
        _check_postgres(c)
    finally:
        c.close()


def _check_postgres(c):
    dbmod.init_schema(c)
    assert c.backend == "postgres"
    assert "enquiries" in c.table_names() and "sex" in c.table_columns("party_members") and "adults_confirmed" in c.table_columns("enquiries")
    c.execute("INSERT INTO settings(key, value) VALUES (?, ?)", ("k1", "a"))
    c.execute("INSERT OR REPLACE INTO settings(key, value) VALUES (?, ?)", ("k1", "b"))
    assert c.execute("SELECT value FROM settings WHERE key=?", ("k1",)).fetchone()[0] == "b"
    c.execute("INSERT OR IGNORE INTO cities(name, active) VALUES ('Melbourne', 1)")
    assert c.execute("SELECT COUNT(*) FROM cities WHERE name='Melbourne'").fetchone()[0] == 1
    c.execute("INSERT INTO match_runs(dataset, started_at) VALUES (?, ?)", ("test", dbmod.now_iso()))
    rid = c.execute("SELECT last_insert_rowid()").fetchone()[0]
    assert rid >= 1
    # a failing statement must not poison the transaction (SQLite behaviour)
    with pytest.raises(Exception):
        c.execute("INSERT INTO no_such_table VALUES (1)")
    assert c.execute("SELECT COUNT(*) FROM match_runs WHERE id=?", (rid,)).fetchone()[0] == 1
    c.commit()


